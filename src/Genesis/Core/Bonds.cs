namespace Genesis.Core
{
    /// <summary>
    /// Общие для всех бэкендов параметры устойчивых связей.
    ///
    /// Связь — это не «K ближайших соседей в этом кадре», а запомненный партнёр.
    /// Она образуется только когда пара уже сблизилась до
    /// <see cref="FormDistanceFactor"/> длин покоя, а рвётся, когда растянулась до
    /// <see cref="BreakDistanceFactor"/> длин покоя. Зазор между этими порогами —
    /// гистерезис: связь не мигает каждый кадр и не восстанавливается сразу после
    /// разрыва, пока частицы снова не сойдутся.
    ///
    /// Пороги считаются от <c>MinDistance</c>, а не от радиуса взаимодействия:
    /// радиус — это дальность «химического сродства», а длина и прочность связи
    /// задаются её собственной длиной покоя.
    /// </summary>
    internal static class Bonds
    {
        /// <summary>
        /// Во сколько раз длина покоя должна быть превышена, чтобы связь образовалась.
        /// </summary>
        public const float FormDistanceFactor = 1.35f;

        /// <summary>Во сколько раз связь может растянуться, прежде чем порвётся.</summary>
        public const float BreakDistanceFactor = 2.0f;
    }
}
